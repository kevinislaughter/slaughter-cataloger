#!/usr/bin/env node
/* Slaughter Cataloger 3 — the app at scale (Stage A4: the A1 audit's PERF-02 and PERF-03, and defect
   DF-14).

   usage: node tools/test-performance.js <app.html>

   Two libraries generated by tools/lib/search-library.js (invented words only, never written to disk):
     wide   50 titles of 20 issues, 10,000 contents items, 2,000 headings (the Phase 2 budget library)
     long   one title with a run of 2,000 issues, 10,000 contents items, 500 headings
   each opened in Chromium from a test folder kept in the page's memory.

   The limit is the one accepted at the Phase 2 closeout for search: 2,000 ms. Every measurement here
   must come in under it, or the run fails, as a severe regression. The figures are printed, and added
   to the runner's performance summary (SC_PERF_SUMMARY). Times are from the action to the page drawn
   (two animation frames after the work), or to the download.
   1  in Node: names.index at full scale gives the same list as the search's own one-pass name list,
      entry for entry, on both libraries (DF-14), within the limit, and within it at twice the scale
      (20,000 items, 4,000 headings); the short-name check over a 2,000-issue run, within the limit;
   2  the wide library and 3 the long library, in the browser:
      • opening the folder; the Library page, Names, a title, its Issues, an issue, Alt+Page Down, a
        new issue and Record, Contents and an issue's grid, typing in a cell; a change (a title edited)
        while each is shown; the Compiler with every title, each HTML output and RIS, and Download of
        the whole library; Save of a few files and of every file; the browser's working copy (a
        change stored, a snapshot of the whole library); a reload restoring the library — each under
        the limit (PERF-02, PERF-03);
      • the Names list is worked out once for each change, not once for the Library tabs and again for
        the view; a change while a long run is shown checks no short name again; the heights of the
        bars that stay in view are not set again when they have not changed;
      • the Compiler's preview: the first 25 issues of one title, fewer of each when several are
        chosen (at least one of each), and the note saying so.
   Fails on any page error or failed check. */
'use strict';
const path = require('path'), fs = require('fs');
let chromium;
try { ({ chromium } = require('playwright')); } catch (e) { ({ chromium } = require(require('child_process').execSync('npm root -g').toString().trim() + '/playwright')); }
const ROOT = path.join(__dirname, '..');
const app = path.resolve(process.argv[2] || path.join(ROOT, 'dist', 'slaughter-cataloger-3.html'));
globalThis.SC = {};
['csv', 'ids', 'schema', 'numbering', 'records', 'store', 'toc', 'names', 'catalog', 'search'].forEach(f => require(path.join(ROOT, 'js', 'core', f + '.js')));
const SCx = globalThis.SC, NM = SCx.names, X = SCx.search, N = SCx.numbering;
const { makeLibrary, toFiles } = require('./lib/search-library');
const LIMIT = 2000;

const log = [], errors = [], perf = [];
let failures = 0, count = 0;
const step = s => log.push('· ' + s);
const expect = (cond, what, detail) => { count++; log.push((cond ? '  ok   ' : '  FAIL ') + what + (cond || detail === undefined ? '' : '\n         ' + String(typeof detail === 'string' ? detail : JSON.stringify(detail)).slice(0, 700))); if (!cond) failures++; };
const ms = t => Math.round(t).toLocaleString('en-US') + ' ms';
// A measurement: under the limit, or the check fails.
const within = (shape, what, t, note) => {
  expect(t <= LIMIT, what + ': ' + ms(t) + (note ? ' (' + note + ')' : ''));
  perf.push('  ' + (shape + ', ' + what + ' ').padEnd(72, '.') + ' ' + ms(t).padStart(9) + (note ? '   ' + note : ''));
};

// The test folder, kept in the page's memory (the generated libraries are never written to disk).
function memoryFolder(seedArg) {
  if (window.top !== window) return;
  const tree = { files: {}, dirs: {} };
  Object.keys(seedArg.files).forEach(n => { tree.files[n] = { text: seedArg.files[n], lastModified: 1000 }; });
  const notFound = () => { const e = new Error('not found'); e.name = 'NotFoundError'; return e; };
  const fileHandle = (node, name) => ({ kind: 'file', name, getFile: async () => ({ name, lastModified: node.files[name].lastModified, text: async () => node.files[name].text }),
    createWritable: async () => { let buf = ''; return { write: async t => { buf += t; }, close: async () => { node.files[name] = { text: buf, lastModified: Date.now() }; }, abort: async () => {} }; } });
  const dirHandle = (node, name) => ({ kind: 'directory', name, queryPermission: async () => 'granted', requestPermission: async () => 'granted',
    values: async function* () { for (const n of Object.keys(node.files)) yield fileHandle(node, n); for (const d of Object.keys(node.dirs)) yield dirHandle(node.dirs[d], d); },
    getFileHandle: async (n, o) => { if (!node.files[n]) { if (!(o && o.create)) throw notFound(); node.files[n] = { text: '', lastModified: Date.now() }; } return fileHandle(node, n); },
    getDirectoryHandle: async (n, o) => { if (!node.dirs[n]) { if (!(o && o.create)) throw notFound(); node.dirs[n] = { files: {}, dirs: {} }; } return dirHandle(node.dirs[n], n); },
    removeEntry: async n => { delete node.files[n]; delete node.dirs[n]; } });
  window.__SC_TEST_FS__ = { root: dirHandle(tree, 'Bench Library'), tree: () => tree };
}

const SHAPES = {
  wide: { opts: {}, label: '50 titles of 20 issues, 10,000 items, 2,000 headings' },
  long: { opts: { titles: 1, issuesPerTitle: 2000, itemsPerIssue: 5, headings: 500 }, label: 'one title of 2,000 issues, 10,000 items, 500 headings' }
};

(async () => {
  const states = {};
  Object.keys(SHAPES).forEach(k => { states[k] = makeLibrary(SHAPES[k].opts); });

  step('1. In Node: names.index at full scale, the same as the search\'s one-pass list (DF-14); the short-name check over a long run');
  {
    const pic = ix => JSON.stringify({ e: ix.entries.map(e => [e.id, e.kind, e.label, e.sort, e.keys, e.forms, e.count, e.authority ? e.authority.authorityID : null]),
      f: Array.from(ix.forms).map(([k, f]) => [k, Array.from(f.forms), f.count, f.items]), h: Array.from(ix.headingOfKey), c: ix.conflicts });
    for (const k of Object.keys(SHAPES)) {
      const st = states[k];
      const t0 = process.hrtime.bigint();
      const ix = NM.index(st);
      const t = Number(process.hrtime.bigint() - t0) / 1e6;
      expect(pic(ix) === pic(X.nameIndex(st)), k + ': names.index (' + ix.entries.length.toLocaleString('en-US') + ' names) is the search\'s name list, entry for entry');
      within(k, 'names.index in Node', t);
    }
    // At twice the budget scale (20,000 items, 4,000 headings), where a list that grew with headings ×
    // forms (DF-14: about 1.5 s at the budget scale in Node) would take several seconds.
    const twice = makeLibrary({ titles: 100, issuesPerTitle: 20, itemsPerIssue: 10, headings: 4000 });
    const t2 = process.hrtime.bigint();
    NM.index(twice);
    within('2x', 'names.index in Node, at 20,000 items and 4,000 headings', Number(process.hrtime.bigint() - t2) / 1e6);
    const run = Array.from(states.long.issues.values());
    const vals = x => ({ volume: x.volume, issue: x.issue, number: x.number, months: x.months, year: x.year });
    const t0 = process.hrtime.bigint();
    run.forEach(i => N.fixShortName(i.shortname, vals(i)));
    within('long', 'the short-name check of all 2,000 issues, in Node', Number(process.hrtime.bigint() - t0) / 1e6);
  }

  const browser = await chromium.launch();
  for (const [n, shape] of [[2, 'wide'], [3, 'long']]) {
    const st = states[shape];
    step(n + '. The ' + shape + ' library in the browser: ' + SHAPES[shape].label + ' (PERF-02, PERF-03)');
    let ctx;
    try {
      const files = toFiles(st);
      const big = Array.from(st.titles.keys()).map(t => [t, Array.from(st.issues.values()).filter(i => i.titleID === t).length]).sort((a, b) => b[1] - a[1])[0][0];
      ctx = await browser.newContext({ viewport: { width: 1360, height: 900 }, acceptDownloads: true });
      await ctx.addInitScript(memoryFolder, { files });
      const page = await ctx.newPage();
      page.on('pageerror', e => errors.push(shape + ': page error: ' + e.message));
      page.on('console', m => { if (m.type() === 'error' && !/fonts\.g|ERR_TUNNEL|net::|Failed to load resource/.test(m.text())) errors.push(shape + ': console: ' + m.text()); });
      page.on('dialog', d => d.accept());
      page.setDefaultTimeout(120000);
      await page.goto('file://' + app);
      await page.waitForSelector('text=Open library folder');
      const drawn = () => page.evaluate(() => new Promise(r => setTimeout(() => requestAnimationFrame(() => requestAnimationFrame(r)), 0)));
      const timed = async fn => { const t0 = Date.now(); await fn(); await drawn(); return Date.now() - t0; };
      const go = (hash, sel) => timed(async () => { await page.evaluate(h => { location.hash = h; }, hash); await page.waitForSelector(sel); });
      // A change (a title's notes edited, as the title page would) while a view is shown, to drawn.
      const change = () => page.evaluate(async () => {
        const s = SC.session.store, tt = Array.from(s.state.titles.values())[0];
        const t0 = performance.now();
        s.put('title', Object.assign({}, tt, { generalNotes: (tt.generalNotes || '') + ' x' }), 'A change');
        await new Promise(r => setTimeout(() => requestAnimationFrame(() => requestAnimationFrame(r)), 0));
        return performance.now() - t0;
      });
      // How often a function of the app's core runs during a change (the page's own copy, wrapped).
      const callsDuring = (obj, fn) => page.evaluate(async ([o, f]) => {
        const target = SC[o], orig = target[f];
        let n = 0;
        target[f] = function () { n++; return orig.apply(this, arguments); };
        try {
          const s = SC.session.store, tt = Array.from(s.state.titles.values())[0];
          s.put('title', Object.assign({}, tt, { generalNotes: (tt.generalNotes || '') + ' y' }), 'A change');
          await new Promise(r => setTimeout(() => requestAnimationFrame(() => requestAnimationFrame(r)), 0));
        } finally { target[f] = orig; }
        return n;
      }, [obj, fn]);

      within(shape, 'opening the folder, to the Library page drawn', await timed(async () => {
        await page.click('text=Open library folder');
        await page.waitForFunction(() => SC.session.ui.mode === 'folder' && !SC.session.ui.busy && document.querySelector('table.shelf tbody tr'));
      }));
      within(shape, 'names.index in the page', await page.evaluate(() => { const t0 = performance.now(); SC.names.index(SC.session.store.state); return performance.now() - t0; }));
      within(shape, 'the Library page: a change, drawn', await change());
      expect(await callsDuring('names', 'index') === 1, shape + ': the Library page: the names worked out once for the change (the Names tab\'s count)');
      within(shape, 'Names: opened', await go('#/names', '.nm-list'));
      within(shape, 'Names: a change, drawn', await change());
      const nIndex = await callsDuring('names', 'index');
      expect(nIndex === 1, shape + ': Names: the names worked out once for a change, not for the tab and again for the view (' + nIndex + ')');
      await page.click('.seg-btn:has-text("Suggested matches")'); await drawn();
      within(shape, 'Names, Suggested matches: a change, drawn', await change());
      within(shape, 'the largest title: opened', await go('#/library/' + big, '.entry-card'));
      within(shape, 'the largest title: a change, drawn', await change());
      const iids = await page.evaluate(t => SC.session.store.issuesOfTitle(t).map(i => i.issueID), big);
      within(shape, 'its Issues (' + iids.length.toLocaleString('en-US') + '): opened', await go('#/issues/' + big, 'table.list tbody tr'));
      within(shape, 'its Issues: a change, drawn', await change());
      const fixes = await callsDuring('numbering', 'fixShortName');
      expect(fixes === 0, shape + ': its Issues: a change elsewhere checks no short name again (' + fixes + ' checked)');
      // A change that adds to the list on screen (a designation tag on its first issue), so that the bars are
      // measured again: their heights have not changed, so none is set again.
      const sets = await page.evaluate(async t => {
        const st = document.documentElement.style, orig = st.setProperty;
        let n = 0, tags = 0;
        st.setProperty = function () { n++; return orig.apply(this, arguments); };
        try {
          const s = SC.session.store, first = s.issuesOfTitle(t)[0];
          s.put('issue', Object.assign({}, first, { issueDesignation: 'Extra' }), 'A change');
          await new Promise(r => setTimeout(() => requestAnimationFrame(() => requestAnimationFrame(() => requestAnimationFrame(r))), 0));
          tags = document.querySelectorAll('table.list tbody .tag').length;
        } finally { st.setProperty = orig; }
        return { n, tags };
      }, big);
      expect(sets.tags > 0 && sets.n === 0, shape + ': its Issues: after a change to the list, the bars are measured again and their heights, unchanged, are not set again (' + sets.n + ' set)', sets);
      const mid = iids[Math.floor(iids.length / 2)];
      within(shape, 'an issue: opened', await go('#/issues/' + big + '/' + mid, '.issue-main .field'));
      within(shape, 'an issue: Alt+Page Down to the next', await timed(async () => {
        await page.focus('.issue-main input[type=text]'); await page.keyboard.press('Alt+PageDown');
        await page.waitForFunction(id => location.hash.indexOf(id) !== -1, iids[iids.indexOf(mid) + 1]); await page.waitForSelector('.issue-main .field');
      }));
      within(shape, 'a new issue: opened', await go('#/issues/' + big + '/new', '.draft-card'));
      within(shape, 'a new issue: recorded (Ctrl+Enter)', await timed(async () => {
        await page.focus('.issue-main input[type=text]'); await page.keyboard.press('Control+Enter');
        await page.waitForFunction(x => SC.session.store.issuesOfTitle(x[0]).length === x[1] + 1, [big, iids.length]);
      }));
      within(shape, 'Contents, the issue list: opened', await go('#/contents/' + big, 'table.list tbody tr'));
      within(shape, 'Contents, an issue\'s grid: opened', await go('#/contents/' + big + '/' + mid, 'table.grid-toc'));
      within(shape, 'Contents grid: a letter typed in a title, then Tab', await timed(async () => {
        await page.click('table.grid-toc tbody tr:nth-child(1) .cell >> nth=0'); await page.keyboard.press('End'); await page.keyboard.type('z'); await page.keyboard.press('Tab');
        await page.waitForFunction(id => (SC.session.store.contentsOfIssue(id)[0].itemTitle || '').endsWith('z'), mid);
      }));

      // The Compiler: every title; its preview, and each output downloaded whole.
      within(shape, 'the Compiler: opened', await go('#/compiler', '.cmp-layout'));
      const nTitles = st.titles.size;
      within(shape, 'the Compiler: every title chosen, preview drawn', await timed(async () => {
        await page.click('.cmp-block-head button:has-text("All")'); await page.waitForSelector('.cmp-bar');
      }));
      for (const name of ['Catalog', 'Proofing catalog', 'Name index', 'RIS']) {
        within(shape, 'the Compiler: ' + name + ', preview drawn', await timed(async () => {
          await page.click('.cmp-output:has(.co-label:text-is("' + name + '"))'); await page.waitForTimeout(30);
        }));
        let size = 0;
        within(shape, 'the Compiler: ' + name + ', Download of the whole library', await timed(async () => {
          const [d] = await Promise.all([page.waitForEvent('download', { timeout: 60000 }), page.click('.cmp-bar button:has-text("Download")')]);
          size = (await fs.promises.stat(await d.path())).size;
        }), (size / 1048576).toFixed(1) + ' MB');
      }
      // The preview's size: 25 issues of one title; fewer of each when several are chosen.
      await page.click('.cmp-output:has(.co-label:text-is("Proofing catalog"))'); await drawn();
      const prev = () => page.evaluate(() => ({ issues: (document.querySelector('.cmp-frame').srcdoc.match(/<section class="proof-issue">/g) || []).length,
        note: (document.querySelector('.cmp-partial') || {}).textContent || '' }));
      const perTitle = Math.max(1, Math.floor(25 / nTitles));
      let p = await prev();
      const total = st.issues.size + 1;          // and the one recorded above
      const wantShown = shape === 'wide' ? nTitles * perTitle : 25;
      expect(p.issues === wantShown, 'the preview of ' + (nTitles > 1 ? 'all ' + nTitles + ' titles' : 'the title') + ': ' + wantShown + ' issues (' + (nTitles > 1 ? perTitle + ' of each' : 'the first 25') + ')', p);
      expect(p.note === (nTitles > 1 ? 'The preview shows the first ' + perTitle + ' issue' + (perTitle === 1 ? '' : 's') + ' of each title, ' + wantShown + ' issues of ' + total.toLocaleString('en-US') + '. Download, Copy and Open include them all.'
        : 'The preview shows the first 25 issues of ' + total.toLocaleString('en-US') + '. Download, Copy and Open include them all.'), 'and the note says so: "' + p.note + '"');
      if (nTitles > 1) {
        await page.click('.cmp-block-head button:has-text("None")'); await page.click('.cmp-title >> nth=0'); await page.click('.cmp-title >> nth=1'); await page.waitForSelector('.cmp-bar'); await drawn();
        p = await prev();
        expect(p.issues === 24 && /^The preview shows the first 12 issues of each title, 24 issues of 4\d\. /.test(p.note), 'two titles of 20 issues or so: 12 of each in the preview, and the note says so', p);
      }

      // Saving, and the browser's working copy.
      await page.evaluate(() => { location.hash = '#/library'; }); await page.waitForSelector('table.shelf');
      await page.evaluate(() => SC.session.flush());
      let dirty = await page.evaluate(() => SC.session.store.dirty.size);
      within(shape, 'Save: ' + dirty + ' changed files', await timed(async () => {
        await page.keyboard.press('Control+s'); await page.waitForFunction(() => SC.session.store.dirty.size === 0 && !SC.session.ui.busy);
      }));
      await page.evaluate(() => { const s = SC.session.store; s.setLibrary({ name: s.state.library.name + ' (renamed)' }, 'Rename library'); });
      dirty = await page.evaluate(() => SC.session.store.dirty.size);
      within(shape, 'Save: the library renamed, ' + dirty + ' changed files', await timed(async () => {
        await page.keyboard.press('Control+s'); await page.waitForFunction(() => SC.session.store.dirty.size === 0 && !SC.session.ui.busy);
      }));
      within(shape, 'the working copy: a change stored', await page.evaluate(async () => {
        await SC.session.flush();
        const s = SC.session.store, tt = Array.from(s.state.titles.values())[0];
        const t0 = performance.now();
        s.put('title', Object.assign({}, tt, { generalNotes: 'stored' }), 'A change');
        await new Promise(r => { const f = () => (SC.session.pendingWrites() ? setTimeout(f, 1) : r()); f(); });
        return performance.now() - t0;
      }));
      within(shape, 'the working copy: a snapshot of the whole library stored', await page.evaluate(async () => { const t0 = performance.now(); await SC.session.compactNow(); return performance.now() - t0; }));
      within(shape, 'a reload: the library restored from the browser, drawn', await timed(async () => {
        await page.reload();
        await page.waitForFunction(() => window.SC && SC.session && SC.session.ui && SC.session.ui.mode === 'folder' && !SC.session.ui.busy && document.querySelector('table.shelf tbody tr'));
      }));
      expect(await page.evaluate(() => SC.session.store.state.contents.size) === st.contents.size + 0 && await page.evaluate(() => / \(renamed\)$/.test(SC.session.store.state.library.name)), 'after the reload, the library as it was: ' + st.contents.size.toLocaleString('en-US') + ' items, the new name');
    } catch (e) {
      failures++; log.push('  FAIL the section stopped: ' + String(e && e.message || e).split('\n')[0]);
    }
    if (ctx) await ctx.close().catch(() => {});
  }
  await browser.close();

  expect(errors.length === 0, 'no page errors', errors.slice(0, 5));
  console.log(log.join('\n'));
  console.log('\nFigures (the limit is ' + LIMIT.toLocaleString('en-US') + ' ms):\n' + perf.join('\n'));
  if (process.env.SC_PERF_SUMMARY) {
    try { fs.appendFileSync(process.env.SC_PERF_SUMMARY, 'The app at scale (tools/test-performance.js), generated libraries; limit ' + LIMIT.toLocaleString('en-US') + ' ms each:\n' + perf.join('\n') + '\n'); } catch (e) { /* the summary is for information */ }
  }
  console.log(failures ? '\nFAILED ' + failures + ' of ' + count + ' checks.' : '\nAll ' + count + ' performance checks passed.');
  process.exit(failures ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
